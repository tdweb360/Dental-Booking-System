def fetchStaffQueryResults(results):
    valid_ids = []
    if len(results) == 0:
        print("No staff members found")
    else:
        for p in results:
            print(f"ID: {p[0]}"
                  f" | Name: {p[1]} {p[2]}"
                  f" | Username: {p[3]}"
                  f" | Role: {p[5]}")
            valid_ids.append(p[0])
        chosenID = selectStaff(valid_ids)
        return chosenID

